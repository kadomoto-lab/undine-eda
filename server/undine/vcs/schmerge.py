"""Three-way merge and semantic diff of Xschem schematics (`<cell>.sch`, kind "schematic") and symbols (`<cell>.sym`,
kind "symbol"); docs/design/merge.md.

Each side is parsed with the Xschem model (xschem.parse) and the merged model is written with the editor's writer
(xschem.dump). A merged model equal to ours' keeps ours' bytes, equal to theirs' theirs' bytes, so formatting (a
multi-line attribute list, an empty K record) and the order of objects are never churned by a merge. What merges, by
which identity, and the conflict ids:

    instance   named: by its name (xschem.comp_ids); delete / modify, both added differently  "inst:M1"
               the name: renamed on a side (a base instance gone and one only that side has,   "rename:M1"
               same symbol and placement, paired like oplog.diff) it keeps its base
               identity, so the other side's changes follow it to the new name
               the symbol one value                                                            "inst:M1:sym"
               the placement (x, y, rotation, flip) one value                                  "inst:M1:placement"
               the other properties one value each                                             "inst:M1:prop:W"
               an embedded symbol one value (compared as written)                              "inst:M1:embedded"
               unnamed: by its whole value, merged by region (below)                           "inst:@<sym>@<x>,<y>,
                                                                                               <rot>,<flip>#<hash>"
    ports      the sequence of the port instances (ipin / opin / iopin) in file order, by      "ports"
               identity: one value (it is the subcircuit's pin order)
    wire       by its end points (xschem.wire_id) and properties, merged by region (below)     "wire:0,0,10,0 lab=Y"
    text       by its whole value (string, position, rotation, flip, sizes, properties, as     "text:{A} -35 -6 0 0
               Xschem writes them), merged by region (below)                                   0.2 0.2 {}"
    drawing    lines, boxes, polygons, arcs: one value per collection (layer-5 boxes are the   "drawing:boxes"
               symbol's pins, in pin order)
    K record   per attribute; written as the side wrote it when the merged attributes are      "K:format"
               that side's, else regenerated by the writer
    G, v       one value each                                                                  "G", "version"
    V S E F    per block, one value each                                                       "code:S"

Names tie the schematic to its netlist and layout, so a merge never renames anything itself:
- both sides adding one name with different content is the conflict "inst:<name>" (ours' instance kept);
- a merged file in which two instances have one name that neither side gave both (ours renamed A to N, theirs added
  N) is the conflict "name:<N>": the instance that has N on ours keeps it, the other gets back its name on ours (or is
  left out when ours does not have it); resolved to theirs, the other way round. A name a side already gave to
  several instances is a warning.
Unnamed instances, wires and texts have no identity but their value (a wire: its end points, either direction, and its
properties; a text: all of it), so an edit of one is a removed and an added one. They merge region by region
(merge3.regions): changed ones that touch (instances at one position; wires with an end point on, or crossing, each
other; texts at one position), and an object a side removed with the nearest copy of it that side added (a move: same
symbol and properties; a wire of the same direction and length; any text), are one region. A region one side
changed is taken from it; both sides changing one differently is one conflict ("inst:@<sym>@...", "wire:<first
removed wire>", "text:<first removed text>"), decided for the whole region: never one instance, wire or text in two
versions, never a deletion lost to the other side's move, and a wire relabelled on one side and rerouted on the other
(a text moved on one side and rewritten or resized on the other) is a conflict, not both. Named instances of one symbol
that ours and theirs each placed at one position (added, moved there, or given that symbol there) while the other side
left them as base had them are a warning (likely one device placed twice).

Order: ours' order, an object only theirs added after its predecessor in theirs (merge3.order); when ours kept base's
objects in base's order, theirs' order (a reordering is a change too). The ports are the exception, because their order
is the subcircuit's pin order (schematic.extract lists them in file order; xschem.canonical never sorts instances): the
sequence of port instances is one value ("ports": a side reordering, adding or removing ports changes it; both sides
changing it differently is a conflict, ours' sequence kept), and the merged ports take the places ports have in the
merged order, in that sequence. A schematic both sides wrote in Undine's canonical order (xschem.canonical: wires and
texts sorted by geometry) stays in it.

diff(old, new) lists changes value by value with the merge's identities ("inst:M1:placement", "inst:M1:prop:W",
"ports" ...), except that a wire is shown by its end points ("wire:<id>" added or removed, "wire:<id>:prop:lab" for a
relabelled one) and a text by its position and string, field by field ("text:<x>,<y>,<string>" added or removed,
"text:<id>:xs", "text:<id>:prop:layer"; a repeated one `<id>#2`), which reads better than a removed and an added one.
Reordering other than of the ports, formatting, and a wire drawn the other way round are no change.
"""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from functools import lru_cache
from pathlib import Path, PurePosixPath
from typing import Any, Callable, Iterable

from undine.schematics import xschem
from undine.schematics.schematic import PORT_TYPES
from undine.schematics.xschem import XComp, XFile, XText
from undine.store.oplog import _comp_obj, _drawing_json, _text_id, _text_obj, _wire_obj
from undine.vcs import merge3
from undine.vcs.merge3 import MISSING, Merge, Result, describe, mapping, regions

KINDS = {"schematic": ".sch", "symbol": ".sym"}
DRAWING = ("lines", "boxes", "polys", "arcs")
PLACEMENT = ("x", "y", "rot", "flip")
TEXT_FIELDS = ("rot", "flip", "xs", "ys")


def kind_of(path: str | Path) -> str | None:
    """"schematic" or "symbol" for a file name of that view, else None."""
    suffix = Path(str(path)).suffix
    return next((k for k, s in KINDS.items() if s == suffix), None)


def _kind(kind: str | None, path: str | Path | None) -> str:
    k = kind or (kind_of(path) if path is not None else None)
    if k not in KINDS:
        raise ValueError(f"not an Xschem view: {kind or path!r} (schematic or symbol)")
    return k


def read(data: bytes | None) -> XFile:
    """The model of a file (an empty one for a file that does not exist)."""
    return xschem.parse(data.decode("utf-8", "replace")) if data is not None else XFile()


# ---------------------------------------------------------------- identities


def _where(c: dict) -> tuple:
    return (c["sym"], c["x"], c["y"], c["rot"], c["flip"])


def _place(c: dict) -> tuple:
    return tuple(c[k] for k in PLACEMENT)


def _show_place(v: Any) -> Any:
    return describe(v if v is MISSING else dict(zip(PLACEMENT, v)))


def _rest(c: dict) -> dict:
    """An instance's properties except its name (the name is its identity, merged on its own)."""
    return {k: v for k, v in c["props"].items() if k != "name"}


def _ukey(c: dict) -> str:
    """An unnamed instance's key: where it is, and a hash of its whole value (equal ones are one multiset element)."""
    h = hashlib.sha1(json.dumps(c, sort_keys=True).encode()).hexdigest()[:8]
    return f"@{c['sym']}@{c['x']:g},{c['y']:g},{c['rot']},{c['flip']}#{h}"


def _insts(f: XFile) -> list[tuple[tuple, dict]]:
    """(key, _comp_obj) of each instance in file order: ("n", identity) for a named one, ("u", value key, n) for the
    n-th unnamed one with that value."""
    seen: Counter = Counter()
    out = []
    for i, c in zip(xschem.comp_ids(f), f.comps):
        o = _comp_obj(c)
        if c.props.get("name"):
            out.append((("n", i), o))
        else:
            u = _ukey(o)
            seen[u] += 1
            out.append((("u", u, seen[u]), o))
    return out


def _named(items: list[tuple[tuple, dict]]) -> dict[str, dict]:
    return {k[1]: v for k, v in items if k[0] == "n"}


def _unnamed(items: list[tuple[tuple, dict]]) -> Counter:
    return Counter(k[1] for k, _ in items if k[0] == "u")


def _rekey(base: dict[str, dict], items: list[tuple[tuple, dict]]) -> list[tuple[tuple, dict]]:
    """A side's instances with renamed ones keyed by their base identity: a base instance the side no longer has and an
    instance only the side has, with the same symbol and placement, are one instance renamed (oplog.diff's pairing)."""
    side = _named(items)
    new = [k for k in side if k not in base]
    ren: dict[str, str] = {}
    for kb in base:
        if kb in side:
            continue
        for ks in new:
            if ks not in ren and _where(base[kb]) == _where(side[ks]):
                ren[ks] = kb
                break
    return [(("n", ren.get(k[1], k[1])), v) if k[0] == "n" else (k, v) for k, v in items]


def _keyed(items: Iterable[tuple[str, Any]]) -> dict[str, Any]:
    """Objects by identity, in order; the n-th one with an identity an earlier one has is `<id>#<n>`."""
    out: dict[str, Any] = {}
    for k, v in items:
        key, n = k, 1
        while key in out:
            n += 1
            key = f"{k}#{n}"
        out[key] = v
    return out


@lru_cache(maxsize=256)
def _sym_type(sym: str, embedded: str | None) -> str:
    """A symbol's type as far as a file alone tells it: an embedded symbol's K type, else the symbol's file name
    (devices/ipin.sym: ipin). The merge has no symbol libraries to read the type from, as schematic.extract does."""
    return xschem.parse(embedded).global_props.get("type", "") if embedded is not None else PurePosixPath(sym).stem


def _is_port(c: dict) -> bool:
    """Whether an instance (a _comp_obj) is a port of the subcircuit (schematic.PORT_TYPES, extract's test)."""
    return _sym_type(c["sym"], c.get("embedded")) in PORT_TYPES


def _ports(items: list[tuple[tuple, dict]]) -> list[tuple]:
    """The keys of the port instances, in file order: the subcircuit's pin order."""
    return [k for k, v in items if _is_port(v)]


def _show_ports(v: Any) -> Any:
    return describe(v if v is MISSING else [k[1] for k in v])


def _wires(f: XFile) -> dict[str, tuple]:
    return _keyed((xschem.wire_id(*w[:4]), w) for w in f.wires)


def _span(w: tuple) -> tuple:
    """A wire's vector from its lower end point: equal for a translated copy, whichever way either is drawn."""
    (x1, y1), (x2, y2) = sorted([(w[0], w[1]), (w[2], w[3])])
    return round(x2 - x1, 6), round(y2 - y1, 6)


def _texts(f: XFile) -> dict[str, XText]:
    return _keyed((_text_id(t), t) for t in f.texts)


def _pins(boxes: list) -> list[str]:
    return [b[5].get("name", "") for b in boxes if b[0] == xschem.PIN_LAYER]


def _drawing_what(kind: str, name: str) -> str:
    return "drawing: boxes (the pins and their order)" if kind == "symbol" and name == "boxes" else f"drawing: {name}"


def _order(b: Iterable, o: Iterable, t: Iterable, keep: set) -> list:
    """merge3.order, except that when ours has base's objects in base's order, theirs' order is taken (theirs may
    have reordered them, and ours did not)."""
    b, o, t = list(b), list(o), list(t)
    return merge3.order(b, t, o, keep) if o == b else merge3.order(b, o, t, keep)


# ---------------------------------------------------------------- merge


def merge(base: bytes | None, ours: bytes, theirs: bytes, prefer: dict[str, str] | None = None,
          kind: str | None = None, path: str | Path | None = None, **kw) -> Result:
    """Merges a schematic or symbol file; `kind` names the view, or `path` does by its suffix."""
    k = _kind(kind, path)
    m = Merge(prefer)
    b, o, t = read(base), read(ours), read(theirs)
    f = XFile(version=m.value("version", "version", b.version, o.version, t.version),
              g_text=m.value("G", "G record", b.g_text, o.g_text, t.g_text))
    f.global_props = mapping(m, "K:", "attribute ", b.global_props, o.global_props, t.global_props)
    # K as a side wrote it (with its G: older symbols keep their attributes in G); else regenerated, which the writer
    # does itself only when G is empty
    same = [x.k_raw for x in (o, t, b) if (x.global_props, x.g_text) == (f.global_props, f.g_text)]
    f.k_raw = same[0] if same else xschem.dump_props(f.global_props) if f.g_text and f.global_props else ""
    f.code = mapping(m, "code:", "code block ", b.code, o.code, t.code)
    for name in DRAWING:
        sides = [getattr(x, name) for x in (b, o, t)]
        bj, oj, tj = (_drawing_json(s) for s in sides)
        v = m.value(f"drawing:{name}", _drawing_what(k, name), bj, oj, tj)
        setattr(f, name, list(sides[1] if v == oj else sides[2] if v == tj else sides[0]))
    f.comps = _merge_comps(m, b, o, t)
    f.wires = _merge_wires(m, b, o, t)
    f.texts = _merge_texts(m, b, o, t)
    if k == "schematic":
        for name in ("wires", "texts"):
            if all(_canonical(getattr(x, name), name) for x in (o, t)):
                xschem.canonical(XFile(**{name: getattr(f, name)}))
    data = ours if f == o else theirs if f == t else xschem.dump(f).encode()
    return m.result(data, k)


def _canonical(items: list, name: str) -> bool:
    """Whether a side's wires / texts are in xschem.canonical's order (Undine writes schematics so)."""
    s = list(items)
    xschem.canonical(XFile(**{name: s}))
    return s == items


def _merge_comps(m: Merge, b: XFile, o: XFile, t: XFile) -> list[XComp]:
    bi = _insts(b)
    bn = _named(bi)
    oi, ti = _rekey(bn, _insts(o)), _rekey(bn, _insts(t))
    on, tn = _named(oi), _named(ti)
    named = mapping(m, "inst:", "instance ", bn, on, tn, lambda k, bv, ov, tv: _merge_inst(m, k, bv, ov, tv))
    objs = {k[1]: v for x in (bi, ti, oi) for k, v in x if k[0] == "u"}

    def at(u: str) -> tuple:
        return objs[u]["x"], objs[u]["y"]
    counts = regions(m, "inst:", "unnamed instances", "instance", *(_unnamed(x) for x in (bi, oi, ti)),
                     _at_one_position(at), lambda u: _ukey({**objs[u], "x": 0, "y": 0}), at,
                     lambda u: f"{objs[u]['sym']} at {objs[u]['x']:g},{objs[u]['y']:g}")
    _unique_names(m, bn, on, tn, named)
    _crowded(m, bn, on, tn, named)
    keep = {("n", i) for i in named} | {("u", u, n) for u, c in counts.items() for n in range(1, c + 1)}
    keys = _order([k for k, _ in bi], [k for k, _ in oi], [k for k, _ in ti], keep)
    vals = {k: named[k[1]] if k[0] == "n" else objs[k[1]] for k in keys}
    keys = _port_order(m, bi, oi, ti, keys, vals)
    embs = {xschem.dump(c.embedded, True): c.embedded for x in (b, t, o) for c in x.comps if c.embedded is not None}
    return [_comp(vals[k], embs) for k in keys]


def _port_order(m: Merge, bi: list, oi: list, ti: list, keys: list, vals: dict) -> list:
    """The merged instance order with the ports in the merged port order. The sequence of port instances (by identity,
    after renames) is one value, "ports": merge3.order would interleave one side's reordering with the other's added
    port into a pin order nobody wrote. The merged ports fill the places ports have in `keys`, in that sequence; one
    it does not list (added on the side not taken, or kept by another conflict) goes after its predecessor there."""
    seq = m.value("ports", "port order (the subcircuit's pin order)", _ports(bi), _ports(oi), _ports(ti), _show_ports)
    cur = [k for k in keys if _is_port(vals[k])]
    it = iter(merge3.order(cur, seq, cur, set(cur)))
    return [next(it) if _is_port(vals[k]) else k for k in keys]


def _merge_inst(m: Merge, k: str, b: Any, o: dict, t: dict) -> dict:
    """A named instance both sides have (or both added): field by field."""
    if o == t:
        return o
    if b is MISSING:                      # never merged field by field, never renamed: names tie netlist and layout
        side = m.conflict(f"inst:{k}", f"instance {k}: added on both sides with different content", b, o, t)
        return t if side == "theirs" else o
    w = f"instance {k}: "
    name = m.value(f"rename:{k}", f"{w}name", b["props"]["name"], o["props"]["name"], t["props"]["name"])
    out = {"sym": m.value(f"inst:{k}:sym", f"{w}symbol", b["sym"], o["sym"], t["sym"])}
    out.update(zip(PLACEMENT, m.value(f"inst:{k}:placement", f"{w}placement", _place(b), _place(o), _place(t),
                                      _show_place)))
    props = list(mapping(m, f"inst:{k}:prop:", w, _rest(b), _rest(o), _rest(t)).items())
    props.insert(list(o["props"]).index("name"), ("name", name))     # where ours has it (first, as Xschem writes)
    out["props"] = dict(props)
    emb = m.value(f"inst:{k}:embedded", f"{w}embedded symbol", b.get("embedded"), o.get("embedded"), t.get("embedded"))
    if emb is not None:
        out["embedded"] = emb
    return out


def _comp(c: dict, embs: dict[str, XFile]) -> XComp:
    e = c.get("embedded")
    return XComp(c["sym"], c["x"], c["y"], c["rot"], c["flip"], dict(c["props"]),
                 None if e is None else embs.get(e) or xschem.parse(e))


def _at_one_position(where: Callable[[Any], tuple]) -> Callable[[list], list]:
    """Changed objects (unnamed instances, texts) at one position (`where`): one region (an object changed there, or
    one placed twice). Each is paired with the first one there, which joins them all."""
    def pairs(changed: list) -> list:
        at: dict = {}
        for v in changed:
            at.setdefault(where(v), []).append(v)
        return [(g[0], v) for g in at.values() for v in g[1:]]
    return pairs


def _unique_names(m: Merge, bn: dict, on: dict, tn: dict, named: dict) -> None:
    """Two merged instances with one name that no side gave both: the conflict "name:<name>". The instance that has
    the name on the side taken keeps it; the others get their name on that side back, or are left out without one."""
    by: dict[str, list[str]] = {}
    for i, c in named.items():
        by.setdefault(c["props"]["name"], []).append(i)
    for name, ids in by.items():
        if len(ids) < 2:
            continue
        has = {s: [i for i in ids if i in n and n[i]["props"]["name"] == name]
               for s, n in (("ours", on), ("theirs", tn))}
        if any(len(v) == len(ids) for v in has.values()):     # a side has them all so: not made by the merge
            m.warn(f"instance name {name} is used by {len(ids)} instances (already before the merge)")
            continue
        side = m.conflict(f"name:{name}", f"instance name {name}: given to {len(ids)} instances",
                          [bn[i] for i in ids if i in bn], [on[i] for i in has["ours"]], [tn[i] for i in has["theirs"]])
        src = on if side == "ours" else tn
        for i in ids:
            if i in has[side]:
                continue
            if i in src:
                named[i] = {**named[i], "props": {**named[i]["props"], "name": src[i]["props"]["name"]}}
            else:
                del named[i]


def _crowded(m: Merge, bn: dict, on: dict, tn: dict, named: dict) -> None:
    """Named instances of one symbol that ours and theirs each placed at one position (layoutmerge._warn_same_place):
    not a conflict, but likely one device placed twice."""
    ours, theirs = _placed_alone(bn, on, tn, named), _placed_alone(bn, tn, on, named)
    for key in sorted(ours.keys() & theirs.keys(), key=str):
        sym, x, y = key
        m.warn(f"instances of {sym} placed at {x:g},{y:g} on both sides: ours {', '.join(ours[key])}, theirs "
               f"{', '.join(theirs[key])}: check they are not one device placed twice")


def _placed_alone(bn: dict, xn: dict, yn: dict, named: dict) -> dict[tuple, list[str]]:
    """The merged named instances that side x placed (added, moved, or gave another symbol) and side y left as base had
    them, with x's placement: {(symbol, x, y): their names}."""
    def put(c: dict | None) -> tuple | None:
        return None if c is None else (c["sym"], *_place(c))
    got: dict[tuple, list[str]] = {}
    for i, c in named.items():
        was, mine = put(bn.get(i)), put(xn.get(i))
        if mine not in (None, was) and put(yn.get(i)) == was and put(c) == mine:
            got.setdefault(mine[:3], []).append(c["props"]["name"])
    return got


def _merge_wires(m: Merge, b: XFile, o: XFile, t: XFile) -> list[tuple]:
    """Wires by region (merge3.regions): a wire is its end points and properties, so an edit of one (moved, stretched,
    rerouted, relabelled) is a removed and an added wire; wires that touch are one region, and so are a wire a side
    removed and the nearest copy of it (same direction and length) that side added: a move."""
    sides = [_wire_values(x) for x in (b, o, t)]
    drawn = {v: w for x in reversed(sides) for v, w in x.items()}   # as ours drew it, else theirs, else base
    counts = regions(m, "wire:", "wires", "wire", *(Counter(map(_wire_value, x.wires)) for x in (b, o, t)),
                     _wires_touching(drawn),
                     lambda v: _span(drawn[v]), lambda v: min((drawn[v][0], drawn[v][1]), (drawn[v][2], drawn[v][3])),
                     lambda v: v)
    keys = _order(*(list(x) for x in sides), set(counts))
    return [drawn[v] for v in keys for _ in range(counts[v])]


def _wire_values(f: XFile) -> dict[str, tuple]:
    """{value: wire} in file order: the value is the end points (xschem.wire_id: either direction) and the properties;
    a repeated one appears once (its count is how often)."""
    out: dict[str, tuple] = {}
    for w in f.wires:
        out.setdefault(_wire_value(w), w)
    return out


def _wire_value(w: tuple) -> str:
    return xschem.wire_id(*w[:4]) + (" " + xschem.dump_props(w[4]).strip() if w[4] else "")


def _wires_touching(drawn: dict[str, tuple]) -> Callable[[list], list]:
    """Changed wires that touch: an end point on the other wire, or crossing it (a junction Xschem may make). The pairs
    to test come from a uniform grid over the wires' bounding boxes (a cell as long as the median wire, at least 1;
    longer when long diagonal wires would fill too many cells): two wires are tested once, in the cell of the lower
    left corner of their bounding boxes' overlap, and only when the boxes overlap."""
    def pairs(changed: list) -> list:
        boxes = []
        for v in changed:
            w = drawn[v]
            boxes.append((min(w[0], w[2]), min(w[1], w[3]), max(w[0], w[2]), max(w[1], w[3])))
        if not boxes:
            return []
        cell = max(sorted(max(x1 - x0, y1 - y0) for x0, y0, x1, y1 in boxes)[len(boxes) // 2], 1)

        def span(lo: float, hi: float) -> range:
            return range(int(lo // cell), int(hi // cell) + 1)
        while sum(len(span(x0, x1)) * len(span(y0, y1)) for x0, y0, x1, y1 in boxes) > _GRID_CELLS * len(boxes):
            cell *= 2
        grid: dict = {}
        for i, (x0, y0, x1, y1) in enumerate(boxes):
            for gx in span(x0, x1):
                for gy in span(y0, y1):
                    grid.setdefault((gx, gy), []).append(i)
        out = []
        for (gx, gy), members in grid.items():
            for k, i in enumerate(members):
                a = boxes[i]
                for j in members[k + 1:]:
                    c = boxes[j]
                    x, y = max(a[0], c[0]), max(a[1], c[1])          # the overlap's lower left corner
                    if (x <= min(a[2], c[2]) and y <= min(a[3], c[3]) and (x // cell, y // cell) == (gx, gy)
                            and _segments_touch(drawn[changed[i]], drawn[changed[j]])):
                        out.append((changed[i], changed[j]))
        return out
    return pairs


_GRID_CELLS = 16        # grid cells the changed wires may cover, per wire


def _segments_touch(a: tuple, c: tuple) -> bool:
    def orient(p, q, r) -> float:
        return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])

    def on(p, q, r) -> bool:            # r on segment p-q, given collinear
        return min(p[0], q[0]) <= r[0] <= max(p[0], q[0]) and min(p[1], q[1]) <= r[1] <= max(p[1], q[1])
    p1, p2, p3, p4 = (a[0], a[1]), (a[2], a[3]), (c[0], c[1]), (c[2], c[3])
    d1, d2, d3, d4 = orient(p3, p4, p1), orient(p3, p4, p2), orient(p1, p2, p3), orient(p1, p2, p4)
    if ((d1 > 0) != (d2 > 0) and d1 and d2) and ((d3 > 0) != (d4 > 0) and d3 and d4):
        return True
    return ((not d1 and on(p3, p4, p1)) or (not d2 and on(p3, p4, p2)) or (not d3 and on(p1, p2, p3))
            or (not d4 and on(p1, p2, p4)))


def _merge_texts(m: Merge, b: XFile, o: XFile, t: XFile) -> list[XText]:
    """Texts by region (merge3.regions), like wires: a text is its whole value (string, position, rotation, flip,
    sizes, properties), so an edit of one (moved, rewritten, resized) is a removed and an added text; changed texts at
    one position are one region, and so are a text a side removed and the nearest text that side added, whatever it
    changed (moved, rewritten, resized: a schematic has few texts, so pairing any two is cheap and only errs toward a
    conflict). A text moved on one side and rewritten on the other is one conflict, never two texts."""
    sides = [_text_values(x) for x in (b, o, t)]
    drawn = {v: x for side in reversed(sides) for (v, _), x in side.items()}   # ours' text, else theirs', else base's
    counts = regions(m, "text:", "texts", "text", *(Counter(v for v, _ in x) for x in sides),
                     _at_one_position(lambda v: (drawn[v].x, drawn[v].y)), lambda v: "text",
                     lambda v: (drawn[v].x, drawn[v].y), lambda v: v)
    keep = {(v, n) for v, c in counts.items() for n in range(1, c + 1)}
    return [XText(**_text_obj(drawn[v])) for v, _ in _order(*(list(x) for x in sides), keep)]


def _text_values(f: XFile) -> dict[tuple[str, int], XText]:
    """{(value, n): text} in file order, for the n-th text with that value (a repeated one keeps its place)."""
    seen: Counter = Counter()
    out: dict[tuple[str, int], XText] = {}
    for x in f.texts:
        v = _text_value(x)
        seen[v] += 1
        out[v, seen[v]] = x
    return out


def _text_value(x: XText) -> str:
    """A text's value as Xschem writes it ("{A} -35 -6 0 0 0.2 0.2 {}")."""
    return (f"{{{xschem._esc(x.s)}}} {xschem._n(x.x)} {xschem._n(x.y)} {x.rot} {x.flip} {xschem._n(x.xs)} {xschem._n(x.ys)} "
            f"{{{xschem._esc(xschem.dump_props(x.props))}}}")



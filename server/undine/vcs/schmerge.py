def diff(old: bytes | None, new: bytes | None, kind: str | None = None, path: str | Path | None = None,
         **kw) -> dict:
    """What changed from `old` to `new`, value by value, with the merge's identities and ids."""
    k = _kind(kind, path)
    a, b = read(old), read(new)
    out: list[dict] = []
    if a.version != b.version:
        _change(out, "version", "version", a.version or MISSING, b.version or MISSING)
    if a.g_text != b.g_text:
        _change(out, "G", "G record", a.g_text or MISSING, b.g_text or MISSING)
    _diff_map(out, "K:", "attribute ", a.global_props, b.global_props)
    _diff_map(out, "code:", "code block ", a.code, b.code)
    for name in DRAWING:
        x, y = getattr(a, name), getattr(b, name)
        if _drawing_json(x) != _drawing_json(y):
            what = _drawing_what(k, name)
            if name == "boxes" and _pins(x) != _pins(y):
                what += f": pins {', '.join(_pins(x)) or '-'} -> {', '.join(_pins(y)) or '-'}"
            _change(out, f"drawing:{name}", what, _drawing_json(x) or MISSING, _drawing_json(y) or MISSING)
    _diff_insts(out, a, b)
    wa, wb = _wires(a), _wires(b)
    for i in _keys(wa, wb):
        x, y = wa.get(i, MISSING), wb.get(i, MISSING)
        if x is MISSING or y is MISSING:
            _change(out, f"wire:{i}", f"wire {i}", _obj(_wire_obj, x), _obj(_wire_obj, y))
        else:
            _diff_map(out, f"wire:{i}:prop:", f"wire {i}: ", x[4], y[4])
    ta, tb = _texts(a), _texts(b)
    for i in _keys(ta, tb):
        x, y = ta.get(i, MISSING), tb.get(i, MISSING)
        if x is MISSING or y is MISSING:
            _change(out, f"text:{i}", f"text {i}", _obj(_text_obj, x), _obj(_text_obj, y))
            continue
        for fld in TEXT_FIELDS:
            if getattr(x, fld) != getattr(y, fld):
                _change(out, f"text:{i}:{fld}", f"text {i}: {fld}", getattr(x, fld), getattr(y, fld))
        _diff_map(out, f"text:{i}:prop:", f"text {i}: ", x.props, y.props)
    return {"kind": k, "changes": out}


def _keys(a: dict, b: dict) -> list:
    """The new order, with what was deleted where it was."""
    return merge3.order(list(a), list(b), list(a), set(a) | set(b))


def _obj(to_json: Callable[[Any], dict], v: Any) -> Any:
    return v if v is MISSING else to_json(v)


def _change(out: list[dict], cid: str, what: str, before: Any, after: Any,
            show: Callable[[Any], Any] = describe) -> None:
    do = "add" if before is MISSING else "del" if after is MISSING else "mod"
    out.append({"do": do, "id": cid, "what": what, "before": show(before), "after": show(after)})


def _diff_map(out: list[dict], prefix: str, what: str, a: dict, b: dict) -> None:
    for k in _keys(a, b):
        x, y = a.get(k, MISSING), b.get(k, MISSING)
        if x != y:
            _change(out, f"{prefix}{k}", f"{what}{k}", x, y)


def _diff_insts(out: list[dict], a: XFile, b: XFile) -> None:
    ai = _insts(a)
    an = _named(ai)
    bi = _rekey(an, _insts(b))
    bn = _named(bi)
    for i in _keys(an, bn):
        x, y = an.get(i, MISSING), bn.get(i, MISSING)
        if x == y:
            continue
        if x is MISSING or y is MISSING:
            _change(out, f"inst:{i}", f"instance {i}", x, y)
            continue
        w = f"instance {i}: "
        if x["props"]["name"] != y["props"]["name"]:
            _change(out, f"rename:{i}", f"{w}name", x["props"]["name"], y["props"]["name"])
        if x["sym"] != y["sym"]:
            _change(out, f"inst:{i}:sym", f"{w}symbol", x["sym"], y["sym"])
        if _place(x) != _place(y):
            _change(out, f"inst:{i}:placement", f"{w}placement", _place(x), _place(y), _show_place)
        _diff_map(out, f"inst:{i}:prop:", w, _rest(x), _rest(y))
        if x.get("embedded") != y.get("embedded"):
            _change(out, f"inst:{i}:embedded", f"{w}embedded symbol", x.get("embedded", MISSING),
                    y.get("embedded", MISSING))
    ua, ub = _unnamed(ai), _unnamed(bi)
    objs = {k[1]: v for x in (ai, bi) for k, v in x if k[0] == "u"}
    for u in _keys(ua, ub):
        if ua[u] == ub[u]:
            continue
        c = objs[u]
        what = f"unnamed instance {c['sym']} at {c['x']:g},{c['y']:g}"
        if ua[u] and ub[u]:
            _change(out, f"inst:{u}", f"{what}: copies", ua[u], ub[u])
        else:
            n = ua[u] or ub[u]
            _change(out, f"inst:{u}", what + (f" ({n} copies)" if n > 1 else ""), c if ua[u] else MISSING,
                    c if ub[u] else MISSING)
    pa, pb = _ports(ai), _ports(bi)      # the pin order: the one instance order that is no formatting
    if pa != pb:
        _change(out, "ports", "port order (the subcircuit's pin order)", pa or MISSING, pb or MISSING, _show_ports)
